defmodule Mix.Tasks.Auix.Gen.StylesheetTest do
  use ExUnit.Case, async: false

  alias Mix.Tasks.Auix.Gen.Stylesheet

  @css_dir "assets/css"
  @variables_file Path.join(@css_dir, "auix-variables.css")
  @rules_file Path.join(@css_dir, "auix-rules.css")
  @combined_file Path.join(@css_dir, "auix-stylesheet.css")
  @custom_file Path.join(@css_dir, "auix-custom.css")
  @baseline_file Path.join(@css_dir, "auix-baseline.css")

  setup context do
    tmp_dir = Map.fetch!(context, :tmp_dir)
    original_dir = File.cwd!()
    File.cd!(tmp_dir)

    on_exit(fn -> File.cd!(original_dir) end)

    {:ok, tmp_dir: tmp_dir}
  end

  @tag :tmp_dir
  test "the default run writes the variables, rules and combined files and no optional file",
       _context do
    Stylesheet.run([])

    assert File.exists?(@variables_file)
    assert File.exists?(@rules_file)
    assert File.exists?(@combined_file)
    refute File.exists?(@custom_file)
    refute File.exists?(@baseline_file)

    shim = File.read!(@combined_file)
    refute shim =~ "auix-custom.css"
    # Tailwind v4 resolves a bare specifier as a package, so the imports must be relative.
    assert shim =~ ~s(@import "./auix-variables.css";)
    assert shim =~ ~s(@import "./auix-rules.css";)
  end

  @tag :tmp_dir
  test "--baseline and --custom each create their file once, keep it, and overwrite it with --force",
       context do
    sentinel = "/* sentinel content */\n"

    Stylesheet.run(["--baseline"])
    baseline = File.read!(@baseline_file)
    assert baseline =~ "/* Generated by auix.gen.stylesheet."
    assert baseline =~ "@layer auix.baseline {"
    assert baseline =~ "html, :host {"

    File.write!(@baseline_file, sentinel)
    Stylesheet.run(["--baseline"])
    assert File.read!(@baseline_file) == sentinel

    Stylesheet.run(["--baseline", "--force"])
    refute File.read!(@baseline_file) == sentinel
    assert File.read!(@baseline_file) =~ "/* Generated by auix.gen.stylesheet."

    Stylesheet.run(["--custom"])
    assert File.exists?(@variables_file)
    assert File.exists?(@rules_file)
    custom = File.read!(@custom_file)

    for marker <- [
          "@layer auix.bridge {",
          ":root, :host {",
          "/* ----- Sizes & dimensions ----- */",
          "/* ----- Typography ----- */",
          "/* ----- Opacity ----- */",
          "/* ----- Shadows & rings ----- */",
          "/* ----- Colors ----- */",
          "/* --auix-border-radius-default:"
        ] do
      assert custom =~ marker
    end

    refute File.read!(@combined_file) =~ "auix-custom.css"

    File.write!(@custom_file, sentinel)
    Stylesheet.run(["--custom"])
    assert File.read!(@custom_file) == sentinel

    Stylesheet.run(["--custom", "--force"])
    refute File.read!(@custom_file) == sentinel
    assert File.read!(@custom_file) =~ "Generated by mix auix.gen.stylesheet"

    # The flags are independent: each one alone creates only its own file.
    File.rm!(@baseline_file)
    File.rm!(@custom_file)
    File.cd!(context.tmp_dir)
    Stylesheet.run(["--baseline"])
    assert File.exists?(@baseline_file)
    refute File.exists?(@custom_file)

    File.rm!(@baseline_file)
    Stylesheet.run(["--custom"])
    assert File.exists?(@custom_file)
    refute File.exists?(@baseline_file)

    File.rm!(@custom_file)
    Stylesheet.run(["--baseline", "--custom"])
    assert File.exists?(@baseline_file)
    assert File.exists?(@custom_file)
  end
end
